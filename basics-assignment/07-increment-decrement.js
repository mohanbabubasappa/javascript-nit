let counter = 5

console.log("Initial value:", counter)

console.log("Post-increment returns:", counter++)
console.log("After post-increment:", counter)

console.log("Pre-increment returns:", ++counter)
console.log("After pre-increment:", counter)

console.log("Post-decrement returns:", counter--)
console.log("After post-decrement:", counter)

console.log("Pre-decrement returns:", --counter)
console.log("After pre-decrement:", counter)
